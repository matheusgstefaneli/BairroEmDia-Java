CREATE SEQUENCE SEQ_MORADOR    START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_CATEGORIA  START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_OCORRENCIA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

CREATE TABLE TB_MORADOR (
    ID_MORADOR  NUMBER(19)     NOT NULL,
    NOME        VARCHAR2(100)  NOT NULL,
    EMAIL       VARCHAR2(150)  NOT NULL,
    CONSTRAINT PK_MORADOR       PRIMARY KEY (ID_MORADOR),
    CONSTRAINT UK_MORADOR_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE TB_CATEGORIA (
    ID_CATEGORIA NUMBER(19)     NOT NULL,
    NOME         VARCHAR2(80)   NOT NULL,
    DESCRICAO    VARCHAR2(255),
    CONSTRAINT PK_CATEGORIA       PRIMARY KEY (ID_CATEGORIA),
    CONSTRAINT UK_CATEGORIA_NOME  UNIQUE (NOME)
);

CREATE TABLE TB_OCORRENCIA (
    ID_OCORRENCIA     NUMBER(19)      NOT NULL,
    TITULO            VARCHAR2(120)   NOT NULL,
    DESCRICAO         VARCHAR2(1000)  NOT NULL,
    LOCALIZACAO       VARCHAR2(255)   NOT NULL,
    PRIORIDADE        NUMBER(1)       NOT NULL,
    STATUS_OCORRENCIA VARCHAR2(20)    NOT NULL,
    DATA_CRIACAO      TIMESTAMP       NOT NULL,
    ID_MORADOR        NUMBER(19)      NOT NULL,
    ID_CATEGORIA      NUMBER(19)      NOT NULL,
    CONSTRAINT PK_OCORRENCIA PRIMARY KEY (ID_OCORRENCIA),
    CONSTRAINT FK_OCORRENCIA_MORADOR   FOREIGN KEY (ID_MORADOR)   REFERENCES TB_MORADOR (ID_MORADOR),
    CONSTRAINT FK_OCORRENCIA_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES TB_CATEGORIA (ID_CATEGORIA),
    CONSTRAINT CK_OCORRENCIA_PRIORIDADE CHECK (PRIORIDADE BETWEEN 1 AND 5),
    CONSTRAINT CK_OCORRENCIA_STATUS CHECK (STATUS_OCORRENCIA IN
        ('ABERTA','EM_ANALISE','EM_ANDAMENTO','RESOLVIDA','CANCELADA'))
);

CREATE INDEX IDX_OCORRENCIA_MORADOR   ON TB_OCORRENCIA (ID_MORADOR);
CREATE INDEX IDX_OCORRENCIA_CATEGORIA ON TB_OCORRENCIA (ID_CATEGORIA);
CREATE INDEX IDX_OCORRENCIA_STATUS    ON TB_OCORRENCIA (STATUS_OCORRENCIA);
